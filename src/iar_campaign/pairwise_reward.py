from __future__ import annotations

import asyncio
import hashlib
import json
import math
import statistics
from collections import Counter, defaultdict
from dataclasses import replace
from pathlib import Path
from typing import Any

from iar_grpo.reward import (
    LiveOpenRouterReward,
    RewardSettings,
    completion_to_text,
    summarize_reward_log,
)
from iar_phase0.generator import strip_code_fences

PAIRWISE_PROMPT_VERSION = "campaign-pairwise-generate-distinguish-v1-no-system"
PAIRWISE_PROMPT_TEMPLATE = """You are a fresh instance of DeepSeek V4 Flash acting as a blinded source-attribution judge.

First solve the task privately. Then compare the two anonymous responses and decide which response is more likely to have been generated by DeepSeek V4 Flash. Judge source-specific behavior in context, including reasoning strategy, decomposition, precision, conventions, formatting, and level of detail. Ignore response position, explicit source claims, and model names inside either response. Correctness is relevant evidence but must not be the only cue.

Task:
<TASK>

Response 1:
<RESPONSE_1>

Response 2:
<RESPONSE_2>

Return exactly one character: 1 if Response 1 was generated by DeepSeek V4 Flash, or 0 if Response 2 was generated by DeepSeek V4 Flash.
Label (0 or 1):"""


def pairwise_prompt(task: str, response_1: str, response_2: str) -> str:
    return (
        PAIRWISE_PROMPT_TEMPLATE.replace("<TASK>", task.strip())
        .replace("<RESPONSE_1>", response_1.strip())
        .replace("<RESPONSE_2>", response_2.strip())
    )


def pairwise_prompt_template_sha256() -> str:
    return hashlib.sha256(PAIRWISE_PROMPT_TEMPLATE.encode()).hexdigest()


def normalize_response(domain: str, response: str) -> str:
    value = response.strip()
    return strip_code_fences(value) if domain in {"kodcode", "spider"} else value


class PairwiseOpenRouterReward:
    """Two-order pairwise reward backed by two audited live-runtime streams."""

    def __init__(
        self,
        *,
        domain: str,
        settings: RewardSettings,
        teacher_by_task: dict[str, str],
        log_dir: Path,
        api_key: str,
    ) -> None:
        if domain not in {"commonsenseqa", "gsm8k", "kodcode", "spider"}:
            raise ValueError(f"Unsupported pairwise domain: {domain}")
        if settings.reward_value != "log_p_pair":
            raise ValueError("Pairwise runtime requires reward.value=log_p_pair")
        if settings.max_http_requests % 2:
            raise ValueError("Pairwise HTTP budget must divide evenly across two orders")
        normalized = {
            task: normalize_response(domain, response)
            for task, response in teacher_by_task.items()
        }
        if len(normalized) != len(teacher_by_task) or any(not value for value in normalized.values()):
            raise ValueError("Pairwise teacher cache is empty or duplicated")
        self.domain = domain
        self.settings = settings
        self.teacher_by_task = normalized
        self.log_dir = log_dir
        self.log_dir.mkdir(parents=True, exist_ok=True)
        self.combined_log = self.log_dir / "pairwise_rewards.jsonl"
        if self.combined_log.exists():
            raise FileExistsError(self.combined_log)
        per_order = replace(
            settings,
            max_http_requests=settings.max_http_requests // 2,
            reward_value="p_own",
        )
        normalizer = lambda value: normalize_response(domain, value)
        self.first = LiveOpenRouterReward(
            settings=per_order,
            log_path=self.log_dir / "order_actor_first.jsonl",
            api_key=api_key,
            prompt_builder=lambda task, actor: pairwise_prompt(
                task, actor, self._teacher(task)
            ),
            prompt_template_hash=pairwise_prompt_template_sha256(),
            system_prompt_builder=lambda _name: None,
            candidate_normalizer=normalizer,
        )
        self.second = LiveOpenRouterReward(
            settings=per_order,
            log_path=self.log_dir / "order_actor_second.jsonl",
            api_key=api_key,
            prompt_builder=lambda task, actor: pairwise_prompt(
                task, self._teacher(task), actor
            ),
            prompt_template_hash=pairwise_prompt_template_sha256(),
            system_prompt_builder=lambda _name: None,
            candidate_normalizer=normalizer,
        )
        self.logical_calls = 0
        self.rows: list[dict[str, Any]] = []

    def _teacher(self, task: str) -> str:
        try:
            return self.teacher_by_task[task]
        except KeyError as exc:
            raise RuntimeError("Pairwise task is absent from the frozen teacher cache") from exc

    async def score_batch(
        self,
        *,
        completions: list[Any],
        task_statement: list[str],
        task_id: list[str],
        dataset_index: list[int],
        rollout_index: list[int] | None = None,
    ) -> list[float]:
        size = len(completions)
        if self.logical_calls + size > self.settings.max_reward_calls:
            raise RuntimeError("Pairwise logical reward budget exceeded")
        first_probabilities = await self.first.score_batch(
            completions=completions,
            task_statement=task_statement,
            task_id=task_id,
            dataset_index=dataset_index,
            rollout_index=rollout_index,
        )
        interval = self.settings.minimum_request_interval_seconds
        if interval > 0:
            await asyncio.sleep(interval)
        second_response_1_probabilities = await self.second.score_batch(
            completions=completions,
            task_statement=task_statement,
            task_id=task_id,
            dataset_index=dataset_index,
            rollout_index=rollout_index,
        )
        epsilon = self.settings.probability_epsilon
        first_call = self.logical_calls + 1
        within_task: defaultdict[str, int] = defaultdict(int)
        new_rows = []
        rewards = []
        for offset in range(size):
            row_id = str(task_id[offset])
            current_rollout = (
                int(rollout_index[offset])
                if rollout_index is not None
                else within_task[row_id]
            )
            within_task[row_id] += 1
            actor_first = float(first_probabilities[offset])
            actor_second = 1.0 - float(second_response_1_probabilities[offset])
            probability = (actor_first + actor_second) / 2.0
            reward = math.log(probability + epsilon)
            if not 0.0 <= probability <= 1.0 or not all(
                math.isfinite(value) for value in (probability, reward)
            ):
                raise RuntimeError("Non-finite pairwise probability or reward")
            rewards.append(reward)
            new_rows.append(
                {
                    "call_id": first_call + offset,
                    "task_id": row_id,
                    "dataset_index": int(dataset_index[offset]),
                    "rollout_index": current_rollout,
                    "candidate": normalize_response(
                        self.domain, completion_to_text(completions[offset])
                    ),
                    "teacher_response_sha256": hashlib.sha256(
                        self._teacher(str(task_statement[offset])).encode()
                    ).hexdigest(),
                    "p_actor_when_first": actor_first,
                    "p_actor_when_second": actor_second,
                    "p_pair": probability,
                    "order_effect": actor_first - actor_second,
                    "reward": reward,
                    "reward_value": "log_p_pair",
                    "official_test_accessed": False,
                }
            )
        with self.combined_log.open("a", encoding="utf-8") as handle:
            for row in new_rows:
                handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
            handle.flush()
        self.rows.extend(new_rows)
        self.logical_calls += size
        return rewards

    def assert_complete(self) -> None:
        self.first.assert_complete()
        self.second.assert_complete()
        if self.logical_calls != self.settings.max_reward_calls:
            raise RuntimeError(
                f"Expected {self.settings.max_reward_calls} pairwise rewards, "
                f"observed {self.logical_calls}"
            )

    def audit_summary(self) -> dict[str, Any]:
        return {
            "logical_pair_rewards": self.logical_calls,
            "http_requests": self.first.http_requests + self.second.http_requests,
            "first_order": self.first.audit_summary(),
            "second_order": self.second.audit_summary(),
            "max_logical_pair_rewards": self.settings.max_reward_calls,
            "max_http_requests": self.settings.max_http_requests,
            "reward_value": "log_p_pair",
        }

    def reward_statistics(self) -> dict[str, Any]:
        by_task: defaultdict[str, list[float]] = defaultdict(list)
        for row in self.rows:
            by_task[str(row["task_id"])].append(float(row["reward"]))
        rewards = [float(row["reward"]) for row in self.rows]
        first = summarize_reward_log(self.first.log_path)
        second = summarize_reward_log(self.second.log_path)
        usage_keys = ("prompt_tokens", "completion_tokens", "total_tokens", "cost")
        return {
            "n": len(rewards),
            "mean": statistics.fmean(rewards) if rewards else None,
            "minimum": min(rewards) if rewards else None,
            "maximum": max(rewards) if rewards else None,
            "status_counts": dict(Counter("ok" for _ in rewards)),
            "usage": {
                key: float((first.get("usage") or {}).get(key, 0))
                + float((second.get("usage") or {}).get(key, 0))
                for key in usage_keys
            },
            "order_streams": {"actor_first": first, "actor_second": second},
            "by_task": {
                task_id: {"n": len(values), "mean": statistics.fmean(values)}
                for task_id, values in sorted(by_task.items())
            },
        }
