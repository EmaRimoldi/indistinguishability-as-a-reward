"""Small, auditable forced-likelihood pilot for Style-vs-Content anchors.

The run deliberately separates three operations:
  1. generate a fresh realization from each selected open-weight model;
  2. score each realization under each model with completion ``echo`` logprobs;
  3. collect counterbalanced pairwise self-attribution choices.

The resulting within-model margin is conditional familiarity under a declared
raw prefix.  It must not be interpreted as a style-only quantity.
"""

from __future__ import annotations

import argparse
import json
import math
import random
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

import numpy as np

from .config import ProjectConfig, load_config
from .env import load_env_file
from .openrouter import OpenRouterClient
from .parameters import initialize_parameter_record


COMPLETIONS_URL = "https://openrouter.ai/api/v1/completions"
ANSWER_RE = re.compile(r"\s*([12])")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument(
        "--launch",
        action="store_true",
        help="Perform the paid API calls. Without this flag, validate inputs only.",
    )
    return parser.parse_args()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def append_jsonl(path: Path, row: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
        handle.flush()


def write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def completion_payload(
    *,
    model_id: str,
    prompt: str,
    max_tokens: int,
    temperature: float,
    top_p: float | None,
    logprobs: int | None,
    echo: bool,
    provider_routing: dict[str, Any],
    request_overrides: dict[str, Any],
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "model": model_id,
        "prompt": prompt,
        "max_tokens": max_tokens,
        "temperature": temperature,
        "echo": echo,
        "provider": provider_routing,
    }
    if top_p is not None:
        payload["top_p"] = top_p
    if logprobs is not None:
        payload["logprobs"] = logprobs
    payload.update(request_overrides)
    return payload


def raw_completion(client: OpenRouterClient, payload: dict[str, Any]) -> dict[str, Any]:
    """Use the completion endpoint while reusing the authenticated client."""
    headers = {
        "Authorization": f"Bearer {client.api_key}",
        "Content-Type": "application/json",
        "X-OpenRouter-Title": "style-vs-content-forced-likelihood",
        "HTTP-Referer": client.site_url,
    }
    # Keep the same retry policy as OpenRouterClient.chat_completion without
    # serializing the secret or a request body to the experiment artifacts.
    import httpx

    last_error: Exception | None = None
    for attempt in range(4):
        try:
            with httpx.Client(timeout=client.timeout_seconds) as http:
                response = http.post(COMPLETIONS_URL, headers=headers, json=payload)
                response.raise_for_status()
                return response.json()
        except Exception as exc:  # noqa: BLE001
            last_error = exc
            if attempt == 3:
                break
            time.sleep(2**attempt)
    raise RuntimeError(f"OpenRouter completion request failed: {last_error}")


def forced_prefix(anchor: str) -> str:
    return (
        "Write a concise, accurate biographical paragraph using only the facts "
        "in the source record. Preserve dates, names, locations, affiliations, "
        "and relations. Do not add unsupported details.\n\n"
        "SOURCE RECORD:\n"
        f"{anchor.strip()}\n\n"
        "BIOGRAPHICAL PARAGRAPH:\n"
    )


def pairwise_prompt(anchor: str, first: str, second: str) -> str:
    return (
        "One of the two candidate paragraphs below was generated by the same "
        "language model that is now answering; the other was generated by a "
        "different model. Which candidate was generated by you? Consider the "
        "whole response. Answer with exactly one character: 1 or 2.\n\n"
        "SOURCE RECORD:\n"
        f"{anchor.strip()}\n\n"
        "CANDIDATE 1:\n"
        f"{first.strip()}\n\n"
        "CANDIDATE 2:\n"
        f"{second.strip()}\n\n"
        "ANSWER:"
    )


def response_text(response: dict[str, Any]) -> str:
    choices = response.get("choices") or []
    if not choices or "text" not in choices[0]:
        raise RuntimeError("Completion response has no choices[0].text")
    return str(choices[0]["text"])


def completion_logprob_check(response: dict[str, Any]) -> dict[str, Any]:
    choices = response.get("choices") or []
    if not choices:
        return {"ok": False, "error": "missing_choices"}
    logprobs = choices[0].get("logprobs")
    if not isinstance(logprobs, dict):
        return {"ok": False, "error": "missing_logprobs"}
    tokens = logprobs.get("tokens")
    token_logprobs = logprobs.get("token_logprobs")
    offsets = logprobs.get("text_offset")
    if not all(isinstance(item, list) for item in (tokens, token_logprobs, offsets)):
        return {"ok": False, "error": "missing_echo_token_arrays"}
    if not (len(tokens) == len(token_logprobs) == len(offsets)):
        return {"ok": False, "error": "inconsistent_echo_token_arrays"}
    finite = [lp for lp in token_logprobs if isinstance(lp, (float, int)) and math.isfinite(lp)]
    return {"ok": bool(finite), "token_count": len(tokens), "finite_logprob_count": len(finite)}


def score_echo(response: dict[str, Any], prefix_length: int) -> dict[str, Any]:
    check = completion_logprob_check(response)
    if not check["ok"]:
        return check
    logprobs = response["choices"][0]["logprobs"]
    selected: list[tuple[str, float, int]] = []
    for token, logprob, offset in zip(
        logprobs["tokens"], logprobs["token_logprobs"], logprobs["text_offset"]
    ):
        if not isinstance(logprob, (float, int)) or not math.isfinite(logprob):
            continue
        # The token that crosses the prefix/candidate boundary is part of the
        # observed continuation and is retained. The protocol records the
        # boundary rule instead of silently discarding it.
        token_end = int(offset) + len(str(token))
        if token_end > prefix_length:
            selected.append((str(token), float(logprob), int(offset)))
    if not selected:
        return {"ok": False, "error": "no_candidate_tokens_after_boundary", **check}
    values = [item[1] for item in selected]
    return {
        "ok": True,
        "mean_logprob": float(np.mean(values)),
        "sum_logprob": float(np.sum(values)),
        "candidate_token_count": len(values),
        "first_candidate_offset": selected[0][2],
        "boundary_rule": "retain token when offset + len(token) > len(prefix)",
        **check,
    }


def parse_choice(response: dict[str, Any]) -> int | None:
    match = ANSWER_RE.match(response_text(response))
    return int(match.group(1)) if match else None


def preflight(
    *,
    client: OpenRouterClient,
    models: list[dict[str, str]],
    cfg: dict[str, Any],
) -> list[dict[str, Any]]:
    probe_prefix = "Return the word hello.\nAnswer:"
    rows: list[dict[str, Any]] = []
    for model in models:
        payload = completion_payload(
            model_id=model["id"],
            prompt=f"{probe_prefix} hello",
            max_tokens=0,
            temperature=0.0,
            top_p=None,
            logprobs=int(cfg["scoring"]["logprobs"]),
            echo=True,
            provider_routing=cfg["provider_routing"],
            request_overrides=cfg.get("request_overrides", {}),
        )
        response = raw_completion(client, payload)
        rows.append(
            {
                "model": model["id"],
                "returned_model": response.get("model"),
                "echo_check": completion_logprob_check(response),
                "usage": response.get("usage"),
            }
        )
    return rows


def summarize(
    generation_rows: Iterable[dict[str, Any]],
    score_rows: Iterable[dict[str, Any]],
    judgment_rows: Iterable[dict[str, Any]],
) -> dict[str, Any]:
    generations = list(generation_rows)
    scores = list(score_rows)
    judgments = list(judgment_rows)
    by_anchor: dict[str, dict[str, float]] = {}
    for row in scores:
        if row.get("score", {}).get("ok"):
            by_anchor.setdefault(str(row["anchor_id"]), {})[str(row["scoring_model"])] = float(
                row["score"]["mean_logprob"]
            )
    model_ids = sorted({str(row["scoring_model"]) for row in scores})
    margins: list[dict[str, Any]] = []
    for anchor_id, values in sorted(by_anchor.items()):
        source_models = sorted({str(row["source_model"]) for row in scores if row["anchor_id"] == anchor_id})
        if len(source_models) != 2:
            continue
        first, second = source_models
        for scorer in model_ids:
            own = scorer
            other = second if scorer == first else first
            own_row = next((r for r in scores if r["anchor_id"] == anchor_id and r["scoring_model"] == scorer and r["source_model"] == own), None)
            other_row = next((r for r in scores if r["anchor_id"] == anchor_id and r["scoring_model"] == scorer and r["source_model"] == other), None)
            if own_row and other_row and own_row["score"].get("ok") and other_row["score"].get("ok"):
                margins.append(
                    {
                        "anchor_id": anchor_id,
                        "model": scorer,
                        "other_model": other,
                        "margin": float(own_row["score"]["mean_logprob"]) - float(other_row["score"]["mean_logprob"]),
                    }
                )
    margin_summary: dict[str, Any] = {}
    for model in model_ids:
        values = [row["margin"] for row in margins if row["model"] == model]
        margin_summary[model] = {
            "n": len(values),
            "mean": float(np.mean(values)) if values else None,
            "own_higher_rate": float(np.mean([value > 0 for value in values])) if values else None,
        }
    readout_summary: dict[str, Any] = {}
    for model in model_ids:
        rows = [row for row in judgments if row["oracle_model"] == model and row["choice"] is not None]
        own_rate = [row["choice"] == row["own_slot"] for row in rows]
        readout_summary[model] = {
            "n": len(rows),
            "own_selection_rate": float(np.mean(own_rate)) if rows else None,
            "first_slot_rate": float(np.mean([row["choice"] == 1 for row in rows])) if rows else None,
        }
    return {
        "generation_count": len(generations),
        "scoring_count": len(scores),
        "judgment_count": len(judgments),
        "margins": margins,
        "by_model": {"forced_likelihood": margin_summary, "readout": readout_summary},
        "interpretation": (
            "Margins estimate conditional familiarity under the declared raw prefix. "
            "They are not a style-only measure; this n=10 pilot is descriptive."
        ),
    }


def main() -> None:
    args = parse_args()
    config: ProjectConfig = load_config(args.config)
    pilot = config.raw["forced_likelihood"]
    anchor_path = Path(pilot["anchors_path"])
    if not anchor_path.exists():
        raise FileNotFoundError(f"Canonical anchor file is unavailable: {anchor_path}")
    anchors = read_jsonl(anchor_path)[: int(pilot["anchor_count"])]
    if len(anchors) != int(pilot["anchor_count"]):
        raise ValueError("Anchor source contains fewer rows than requested.")
    required = {"spec_id", "text"}
    if any(not required.issubset(row) for row in anchors):
        raise ValueError("Anchor records must include spec_id and text.")
    if not args.launch:
        print(json.dumps({"validated": True, "anchor_count": len(anchors), "models": pilot["models"]}, indent=2))
        return

    env_path = config.resolve(config.raw["paths"]["openrouter_env"])
    load_env_file(env_path)
    client = OpenRouterClient.from_env()
    run_id = datetime.now(timezone.utc).strftime(f"{pilot['run_name']}_%Y%m%dT%H%M%SZ")
    out_dir = config.resolve(config.raw["paths"]["experiments"]) / run_id
    out_dir.mkdir(parents=True, exist_ok=False)
    initialize_parameter_record(out_dir, resolved_config=config.raw, source_config=config.path)
    write_jsonl = lambda filename, row: append_jsonl(out_dir / filename, row)

    preflight_rows = preflight(client=client, models=pilot["models"], cfg=pilot)
    write_json(out_dir / "preflight.json", preflight_rows)
    if not all(row["echo_check"]["ok"] for row in preflight_rows):
        raise RuntimeError(f"Echo logprob preflight failed: {preflight_rows}")

    generations: list[dict[str, Any]] = []
    for anchor in anchors:
        prefix = forced_prefix(str(anchor["text"]))
        for model in pilot["models"]:
            payload = completion_payload(
                model_id=model["id"],
                prompt=prefix,
                max_tokens=int(pilot["generation"]["max_tokens"]),
                temperature=float(pilot["generation"]["temperature"]),
                top_p=float(pilot["generation"]["top_p"]),
                logprobs=None,
                echo=False,
                provider_routing=pilot["provider_routing"],
                request_overrides=pilot.get("request_overrides", {}),
            )
            response = raw_completion(client, payload)
            row = {
                "anchor_id": anchor["spec_id"],
                "source_model": model["id"],
                "source_label": model["label"],
                "prefix": prefix,
                "text": response_text(response),
                "returned_model": response.get("model"),
                "usage": response.get("usage"),
            }
            generations.append(row)
            write_jsonl("generations.jsonl", row)

    scores: list[dict[str, Any]] = []
    for generated in generations:
        observed = str(generated["text"])
        full_prompt = str(generated["prefix"]) + observed
        for scorer in pilot["models"]:
            payload = completion_payload(
                model_id=scorer["id"],
                prompt=full_prompt,
                max_tokens=0,
                temperature=0.0,
                top_p=None,
                logprobs=int(pilot["scoring"]["logprobs"]),
                echo=True,
                provider_routing=pilot["provider_routing"],
                request_overrides=pilot.get("request_overrides", {}),
            )
            response = raw_completion(client, payload)
            row = {
                "anchor_id": generated["anchor_id"],
                "source_model": generated["source_model"],
                "scoring_model": scorer["id"],
                "returned_model": response.get("model"),
                "score": score_echo(response, len(str(generated["prefix"]))),
                "usage": response.get("usage"),
            }
            scores.append(row)
            write_jsonl("forced_likelihood_scores.jsonl", row)

    judgments: list[dict[str, Any]] = []
    if pilot["pairwise_readout"]["enabled"]:
        by_anchor = {row["anchor_id"]: {} for row in generations}
        for row in generations:
            by_anchor[row["anchor_id"]][row["source_model"]] = row
        model_ids = [model["id"] for model in pilot["models"]]
        for anchor in anchors:
            pair = by_anchor[str(anchor["spec_id"])]
            first_model, second_model = model_ids
            for oracle in pilot["models"]:
                for own_first in (True, False):
                    own = pair[oracle["id"]]
                    other_model = second_model if oracle["id"] == first_model else first_model
                    other = pair[other_model]
                    first, second = (own, other) if own_first else (other, own)
                    payload = completion_payload(
                        model_id=oracle["id"],
                        prompt=pairwise_prompt(str(anchor["text"]), str(first["text"]), str(second["text"])),
                        max_tokens=int(pilot["pairwise_readout"]["max_tokens"]),
                        temperature=float(pilot["pairwise_readout"]["temperature"]),
                        top_p=None,
                        logprobs=int(pilot["pairwise_readout"]["logprobs"]),
                        echo=False,
                        provider_routing=pilot["provider_routing"],
                        request_overrides=pilot.get("request_overrides", {}),
                    )
                    row = {
                        "anchor_id": anchor["spec_id"],
                        "oracle_model": oracle["id"],
                        "other_model": other_model,
                        "own_slot": 1 if own_first else 2,
                        "choice": parse_choice(response := raw_completion(client, payload)),
                        "returned_model": response.get("model"),
                        "usage": response.get("usage"),
                    }
                    judgments.append(row)
                    write_jsonl("pairwise_readout.jsonl", row)

    summary = summarize(generations, scores, judgments)
    summary.update(
        {
            "run_id": run_id,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "anchor_ids": [row["spec_id"] for row in anchors],
            "random_seed": config.raw["project"]["seed"],
        }
    )
    write_json(out_dir / "summary.json", summary)
    print(json.dumps({"run_dir": str(out_dir), "summary": summary}, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
