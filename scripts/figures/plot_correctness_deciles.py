"""Plot the archived training-rollout deciles, without fitting or resampling.
Source: reward_characterization_attempt003; provenance is in the compact JSON.
These are not scores from the separately evaluated held-out checkpoints.
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parent
DOMAINS = [("commonsenseqa", "CommonsenseQA", "#0072B2"),
           ("gsm8k", "GSM8K", "#E69F00"),
           ("kodcode", "KodCode", "#009E73"),
           ("spider", "Spider", "#CC79A7")]


def plot():
    data = json.loads((ROOT / "correctness_deciles_data.json").read_text())
    seeds_file = ROOT / "correctness_deciles_seeds.json"
    seeds = json.loads(seeds_file.read_text()) if seeds_file.exists() else None
    plt.rcParams.update({"font.family": "DejaVu Sans", "pdf.fonttype": 42,
                         "axes.linewidth": .65})
    fig, ax = plt.subplots(figsize=(3.3, 2.5))
    for domain, label, color in DOMAINS:
        rows = sorted((r for r in data["rows"] if r["domain"] == domain),
                      key=lambda r: r["decile"])
        assert [r["decile"] for r in rows] == list(range(1, 11))
        assert all(r["n"] == 800 for r in rows)
        x = np.array([r["decile"] for r in rows])
        y = np.array([r["correct_rate"] for r in rows])
        low = np.array([r["ci_low"] for r in rows])
        high = np.array([r["ci_high"] for r in rows])
        if seeds is None:
            ax.errorbar(x, y, yerr=np.vstack([y-low, high-y]), color=color,
                        label=label, lw=1.4, marker="o", ms=3.7,
                        elinewidth=.6, capsize=2)
            continue
        # Three seeds, drawn like Figure 2: a thin line per seed under the bold mean.
        per_seed = np.array([[r["correct_rate"] for r in seeds["deciles"][domain][s]]
                             for s in seeds["seeds"]])
        for curve in per_seed:
            ax.plot(x, curve, color=color, lw=.7, alpha=.38, zorder=2)
        ax.plot(x, per_seed.mean(axis=0), color=color, label=label, lw=1.6,
                marker="o", ms=3.4, zorder=3)
    ax.set_title("Correctness by attribution decile", fontsize=9, fontweight="bold", pad=6)
    ax.set_xlabel(r"$p_{\mathrm{ind}}$ decile", fontsize=8, fontweight="bold")
    ax.set_ylabel("Proportion correct", fontsize=8, fontweight="bold")
    ax.set_xticks(range(1, 11))
    ax.set_xlim(.7, 10.3)
    ax.set_ylim(0, 1.0)
    ax.tick_params(labelsize=7.3, length=2.5)
    ax.spines[["top", "right"]].set_visible(False)
    # Separate the one-line legend from the plot so LaTeX can align the table's
    # top rule with the chart title, independently of the legend's height.
    handles, labels = ax.get_legend_handles_labels()
    legend_fig = plt.figure(figsize=(4.6, .3))
    legend_fig.legend(handles, labels, loc="center", ncol=4, frameon=False,
                      fontsize=6.6, columnspacing=1.0, handletextpad=.4)
    legend_fig.savefig(ROOT / "correctness_deciles_legend.pdf",
                       pad_inches=.03)
    plt.close(legend_fig)
    fig.subplots_adjust(left=.15, right=.98, bottom=.21, top=.85)
    fig.canvas.draw()
    crop = fig.get_tightbbox(fig.canvas.get_renderer()).padded(.03)
    top = ax.transData.transform((1, 1.0))[1] / fig.dpi
    # The plot is placed at 0.50 textwidth. Align the table with the 1.0 tick,
    # not with the title. Express the offset in units of the thesis textwidth.
    offset = .50 * (crop.y1 - top) / crop.width
    (ROOT / "correctness_panel_alignment.tex").write_text(
        "% Generated by plot_correctness_deciles.py; do not tune by eye.\n"
        "\\newlength{\\correctnessTableOffset}\n"
        f"\\setlength{{\\correctnessTableOffset}}{{{offset:.8f}\\textwidth}}\n")
    fig.savefig(ROOT / "correctness_by_attribution_decile.pdf",
                bbox_inches="tight", pad_inches=.03)
    plt.close(fig)


if __name__ == "__main__":
    plot()
